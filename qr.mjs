// Minimal QR encoder: byte mode, error level L, versions 1-40.
//
// It exists because the page it serves must make zero network requests, and the
// page it replaces fetched every QR from api.qrserver.com -- which handed a
// third party the entire recipe, in plain text, in a URL.
//
// Error level L only. A share link is long (README.md records 652 base64url
// characters for an 11-ingredient recipe), and L keeps the symbol version, and
// therefore the module size on a phone screen, as large as possible. The codes
// are read off a clean screen, not off a stained printout, so the extra
// redundancy of M/Q/H buys nothing here.
//
// Mask selection follows ISO/IEC 18004 penalty rules N1..N4, so the output is
// byte-identical to independent encoders; tests/qr_test.mjs pins that against
// matrices generated by Nayuki's qrcodegen.

const ECC_L_BITS = 1; // Error level L, as spelled in the format-information field.

