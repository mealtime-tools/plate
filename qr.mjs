/** Unpack one version's block layout from the flat table. */
function eccLayout(version) {
  const [ecLen, count1, data1, count2, data2] = ECC_L[version - 1];
  const groups = [[count1, data1]];
  if (count2 > 0) groups.push([count2, data2]);
  return { ecLen, groups };
}

